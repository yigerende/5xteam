(async () => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const wait = async fn => { for (let i = 0; i < 100; i++) { if (fn()) return; await new Promise(resolve => setTimeout(resolve, 50)) } throw new Error('UI wait timed out') }
  const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text)
  await wait(() => button('席位恢复'))
  button('席位恢复').click()
  await wait(() => document.querySelector('.recovery-table tbody')?.textContent.includes('dwell@example.com'))
  let dwell = [...document.querySelectorAll('.recovery-table tbody tr')].find(r => r.textContent.includes('dwell@example.com'))
  assert(dwell.textContent.includes('2.0 分钟') && dwell.textContent.includes('剩余 3.0 分钟'), 'server clock was not used')
  assert(dwell.textContent.includes('申请') && dwell.textContent.includes('母号同意') && dwell.textContent.includes('退出'), 'snapshot labels incorrect')
  const selects = document.querySelectorAll('.recovery-settings select')
  selects[0].value = 'child_request'; selects[0].dispatchEvent(new Event('change', { bubbles: true }))
  selects[1].value = 'child_leave'; selects[1].dispatchEvent(new Event('change', { bubbles: true }))
  const concurrency = document.querySelector('.recovery-settings input[step="1"]')
  concurrency.value = '100'; concurrency.dispatchEvent(new Event('input', { bubbles: true }))
  assert(concurrency.checkValidity() && !concurrency.hasAttribute('max'), 'AT concurrency still limited to eight')
  button('保存配置').click()
  await wait(() => window.recoveryFixture.settings.join_method === 'child_request')
  assert(window.recoveryFixture.settings.join_method === 'child_request', 'settings not saved')
  assert(window.recoveryFixture.settings.concurrency === 100, 'AT concurrency 100 not saved')
  button('扫描临停').click()
  await wait(() => document.querySelector('.recovery-candidates'))
  assert(document.querySelector('.recovery-candidates').textContent.includes('未进入空间 / 已使用过'), 'candidate match scope label incorrect')
  const boxes = document.querySelectorAll('.recovery-candidates tbody input')
  assert(boxes.length === 2 && boxes[1].disabled, 'ineligible child selectable')
  boxes[0].click()
  await wait(() => button('执行选中 (1)'))
  button('执行选中 (1)').click()
  await wait(() => document.querySelector('.recovery-table').textContent.includes('new@example.com'))
  const fresh = [...document.querySelectorAll('.recovery-table tbody tr')].find(r => r.textContent.includes('new@example.com'))
  assert(fresh.querySelector('.spin') && fresh.textContent.includes('执行中'), 'active step spinner missing')
  assert(window.recoveryFixture.requests.filter(r => r.method === 'POST' && r.path.endsWith('/seat-recovery')).length === 1, 'duplicate starts')
  let failed = [...document.querySelectorAll('.recovery-table tbody tr')].find(r => r.textContent.includes('failed@example.com'))
  assert(failed.textContent.includes('普通席位串行位置已保留'), 'failed lane not visible')
  ;[...failed.querySelectorAll('button')].find(b => b.textContent === '重试').click()
  await wait(() => window.recoveryFixture.tasks.find(p => p.id === 'failed').status === 'running')
  await wait(() => !failed.textContent.includes('失败，待重试'))
  ;[...failed.querySelectorAll('button')].find(b => b.textContent === '日志').click()
  await wait(() => document.querySelector('.recovery-log')?.textContent.includes('HTTP 429'))
  assert(document.querySelector('.recovery-log').textContent.includes('母号专属代理'), 'logs missing source')
  document.querySelector('[aria-label="关闭日志"]').click()
  dwell = [...document.querySelectorAll('.recovery-table tbody tr')].find(r => r.textContent.includes('dwell@example.com'))
  ;[...dwell.querySelectorAll('button')].find(b => b.textContent === '暂停').click()
  await wait(() => dwell.textContent.includes('已暂停'))
  ;[...dwell.querySelectorAll('button')].find(b => b.textContent === '继续').click()
  await wait(() => !dwell.textContent.includes('已暂停'))
  assert(!window.recoveryFixture.requests.some(r => /\/free-accounts|\/auto-rotation|\/sub2/.test(r.path)), 'recovery UI called Team APIs')
  const mother = document.querySelector('[aria-label="恢复席位母号"]')
  assert(!mother.disabled, 'mother selector locked during background execution')
  mother.value = 'mother-two'; mother.dispatchEvent(new Event('change', { bubbles: true }))
  await wait(() => !document.querySelector('.recovery-candidates'))
  assert(window.recoveryFixture.tasks.find(p => p.id === 'new').status === 'running', 'switching mother stopped original task')
  button('扫描临停').click()
  await wait(() => document.querySelector('.recovery-candidates')?.textContent.includes('another@example.com'))
  button('执行全部可恢复 (1)').click()
  await wait(() => document.querySelector('.recovery-table').textContent.includes('another@example.com'))
  assert(window.recoveryFixture.tasks.find(p => p.id === 'another').team_id === 'team-two', 'second mother task used previous workspace')
  assert(window.recoveryFixture.tasks.find(p => p.id === 'new').team_id === 'team', 'original task changed workspace')
  return { ok: true, checks: ['AT concurrency 100', 'switch mother during execution', 'server clock', 'snapshot labels', 'save', 'scan', 'selection', 'progress spinner', 'failure lane', 'retry', 'logs', 'pause/resume', 'Team isolation'] }
})()
