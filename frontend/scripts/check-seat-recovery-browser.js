(async () => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const wait = async fn => { for (let i = 0; i < 160; i++) { if (fn()) return; await new Promise(resolve => setTimeout(resolve, 50)) } throw new Error('UI wait timed out') }
  const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text)
  const row = id => [...document.querySelectorAll('.recovery-table tbody tr')].find(r => r.textContent.includes(id + '@example.com'))
  const fixture = window.recoveryFixture
  const tick = () => new Promise(resolve => setTimeout(resolve, 50))
  const closeProgress = async () => { await wait(() => document.querySelector('[aria-label="恢复批量操作进度"]')?.getAttribute('aria-busy') === 'false'); document.querySelector('[aria-label="关闭操作进度"]').click(); await tick() }
  const confirmations = []
  window.confirm = message => { confirmations.push(message); return true }
  await wait(() => button('席位恢复'))
  button('席位恢复').click()
  await wait(() => row('dwell'))
  assert(row('dwell').textContent.includes('2.0 分钟') && row('dwell').textContent.includes('剩余 3.0 分钟'), 'server clock incorrect')
  const selects = document.querySelectorAll('.recovery-settings select')
  selects[0].value = 'child_request'; selects[0].dispatchEvent(new Event('change', { bubbles: true }))
  selects[1].value = 'child_leave'; selects[1].dispatchEvent(new Event('change', { bubbles: true }))
  const concurrency = document.querySelector('.recovery-settings input[step="1"]')
  concurrency.value = '100'; concurrency.dispatchEvent(new Event('input', { bubbles: true }))
  assert(concurrency.checkValidity() && !concurrency.hasAttribute('max'), 'concurrency capped')
  button('保存配置').click()
  await wait(() => fixture.settings.concurrency === 100)
  button('全选母号').click()
  await wait(() => [...document.querySelectorAll('.recovery-mothers input')].every(p => p.checked))
  button('扫描临停').click()
  await wait(() => document.querySelector('.recovery-candidates tbody')?.querySelectorAll('tr').length === 3)
  const candidateRows = [...document.querySelectorAll('.recovery-candidates tbody tr')]
  assert(candidateRows.find(r => r.textContent.includes('busy@example.com')).querySelector('input').disabled, 'ineligible selectable')
  assert(candidateRows.find(r => r.textContent.includes('another@example.com')).textContent.includes('第二母号'), 'candidate lost mother')
  assert(document.querySelector('.recovery-candidates').textContent.includes('未进入空间 / 已使用过'), 'scope label wrong')
  button('执行全部可恢复 (2)').click()
  await wait(() => row('new') && row('another'))
  assert(row('new').querySelector('.spin'), 'worker spinner missing')
  assert(fixture.tasks.find(p => p.id === 'new').team_id === 'team', 'first workspace wrong')
  assert(fixture.tasks.find(p => p.id === 'another').team_id === 'team-two', 'second workspace wrong')
  assert(fixture.requests.filter(r => r.method === 'POST' && r.path.endsWith('/seat-recovery')).length === 2, 'unexpected creation count')
  const motherBoxes = document.querySelectorAll('.recovery-mothers input')
  assert([...motherBoxes].every(p => !p.disabled), 'background work locks mother selection')
  motherBoxes[0].click()
  await wait(() => !document.querySelector('.recovery-candidates'))
  fixture.failScan = 'mother-two'
  button('扫描临停').click()
  await wait(() => document.querySelector('.recovery-errors')?.textContent.includes('fixture scan failure'))
  assert(fixture.tasks.find(p => p.id === 'new').status === 'running', 'switch mother stopped first job')
  fixture.failScan = ''
  const selectedTasks = ['new', 'another']
  for (const id of selectedTasks) { row(id).querySelector('input[type=checkbox]').click(); await tick() }
  button('批量暂停').click()
  await wait(() => fixture.tasks.filter(p => selectedTasks.includes(p.id)).every(p => p.paused))
  await wait(() => document.querySelector('[aria-label="恢复批量操作进度"]')?.textContent.includes('暂停成功'))
  await closeProgress()
  button('批量继续').click()
  await wait(() => fixture.tasks.filter(p => selectedTasks.includes(p.id)).every(p => !p.paused))
  await closeProgress()
  button('批量踢出').click()
  await wait(() => fixture.tasks.filter(p => selectedTasks.includes(p.id)).every(p => p.manual_remove_method === 'mother_kick'))
  await wait(() => row('new').textContent.includes('手动踢出'))
  assert(document.querySelector('[aria-label="恢复批量操作进度"]').querySelector('.spin'), 'manual progress spinner missing')
  selectedTasks.forEach(id => Object.assign(fixture.tasks.find(p => p.id === id), {stage:'manual_done',status:'completed',finished:true,message:'已确认离开，手动任务结束'}))
  await wait(() => document.querySelector('[aria-label="恢复批量操作进度"]')?.textContent.includes('2 / 2'))
  await closeProgress()
  button('清空选择').click()
  await tick()
  row('dwell').querySelector('input[type=checkbox]').click()
  await tick()
  button('批量退出').click()
  await wait(() => fixture.tasks.find(p => p.id === 'dwell').manual_remove_method === 'child_leave')
  await closeProgress()
  button('清空选择').click()
  await tick()
  row('failed').querySelector('input[type=checkbox]').click()
  await tick()
  ;[...row('failed').querySelectorAll('button')].find(p => p.textContent === '踢出').click()
  await wait(() => fixture.tasks.find(p => p.id === 'failed').manual_remove_method === 'mother_kick')
  await closeProgress()
  ;[...row('dwell').querySelectorAll('button')].find(p => p.textContent === '退出').click()
  await wait(() => fixture.requests.filter(r => r.path.endsWith('batch-control') && r.body.action === 'child_leave').length === 2)
  await closeProgress()
  ;[...row('failed').querySelectorAll('button')].find(p => p.textContent === '日志').click()
  await wait(() => document.querySelector('[aria-label="席位恢复日志"]')?.textContent.includes('母号专属代理'))
  document.querySelector('[aria-label="关闭日志"]').click()
  // Force delete an unfinished occupied task with a manual command underway.
  button('批量删除').click()
  await wait(() => !fixture.tasks.some(p => p.id === 'failed'))
  await wait(() => document.querySelector('[aria-label="恢复批量操作进度"]')?.textContent.includes('删除成功'))
  await closeProgress()
  await wait(() => !row('failed'))
  assert(confirmations.some(p => p.includes('强制删除') && p.includes('任何状态')), 'force-delete confirmation missing')
  assert(!fixture.requests.some(r => /\/free-accounts|\/auto-rotation|\/sub2/.test(r.path)), 'Team API called')
  // Delete completed records in the all-tasks view; selection is cleared on filter change.
  const activeFilter = [...document.querySelectorAll('label')].find(p => p.textContent.trim() === '只看未结束').querySelector('input')
  activeFilter.click()
  await wait(() => row('new') && row('another'))
  for (const id of selectedTasks) { row(id).querySelector('input[type=checkbox]').click(); await tick() }
  button('批量删除').click()
  await wait(() => selectedTasks.every(id => !fixture.tasks.some(p => p.id === id)))
  await closeProgress()
  await wait(() => !row('new') && !row('another'))
  button('全选母号').click()
  await tick()
  button('扫描并执行所选母号').click()
  await wait(() => row('new') && row('another'))
  assert(fixture.requests.filter(r => r.method === 'POST' && r.path.endsWith('/seat-recovery')).length === 4, 'direct multi-mother scan-and-execute failed')
  return {ok:true, checks:['multi-mother scan/start','workspace mapping','partial scan failure','AT concurrency 100','background switching','server clock','batch pause/resume','batch kick/leave','single kick/leave','progress polling','force delete occupied/unfinished task','completed task deletion','logs','Team isolation']}
})()
