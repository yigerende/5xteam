(async () => {
  const fixture = window.gptPayFixture
  if (!fixture) throw new Error('Requires isolated GPTPay preview')
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
  const assert = (ok, text) => { if (!ok) throw new Error(text) }
  const wait = async fn => { for (let i = 0; i < 400; i++) { if (fn()) return; await pause(25) } throw new Error('UI wait timed out') }
  const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text)
  const click = async text => { await wait(() => button(text) && !button(text).disabled); button(text).click(); await pause(80) }
  const field = text => text === '支付国家' ? document.getElementById('pro-payment-country') : [...document.querySelectorAll('label.field')].find(l => l.querySelector('span')?.textContent.trim() === text)?.querySelector('input,select,textarea')
  const fill = async (text, value) => { const el = field(text); assert(el, 'Missing field: ' + text); el.value = value; el.dispatchEvent(new Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); await pause(120) }
  await click('Pro 全自动配置')
  await wait(() => field('开通供应商') && !field('开通供应商').disabled)
  assert(field('开通套餐').querySelector('[value="pro50"]').disabled, 'Tokenseek should not offer unsupported 50x')
  await fill('银行卡默认最大开通数', '7')
  await fill('开通供应商', 'cmsnav')
  await wait(() => field('支付国家') && !field('支付国家').disabled)
  assert(field('GPTPay API 地址').value === 'https://gptpay.cmsnav.com/api/v1', 'New supplier URL not loaded')
  assert(field('GPTPay API Key').value === '' && !field('GPTPay API Key').placeholder.includes('已保存'), 'Supplier key carried over')
  assert(field('银行卡默认最大开通数').value === '7', 'Shared unsaved setting lost')
  await fill('开通套餐', 'pro50'); await fill('支付国家', 'PH'); await fill('GPTPay API Key', 'fixture-new-provider-key')
  await fill('开通供应商', 'tokenseek')
  assert(field('GPTPay API Key').value === '' && field('GPTPay API Key').placeholder.includes('已保存'), 'Old key/profile not isolated')
  await fill('开通供应商', 'cmsnav')
  await wait(() => !field('支付国家').disabled)
  assert(field('开通套餐').value === 'pro50' && field('支付国家').value === 'PH', 'Unsaved provider draft lost')
  await click('保存 Pro 配置')
  await wait(() => fixture.config.provider === 'cmsnav' && fixture.config.plan_code === 'pro50')
  assert(field('GPTPay API Key').value === '', 'Saved API key still in input')
  fixture.cards.push({ id: 'cmsnav-card', name: '测试卡', last4: '4242', exp_year: 2099, exp_month: 12, enabled: true })
  await click('Pro 账号')
  const choose = async title => { document.querySelector('.pro-table [title="更多操作"]').click(); await pause(30); document.querySelector(`.pro-action-menu [title="${title}"]`).click(); await pause(120) }
  await choose('开通 Pro')
  await wait(() => button('确认开通 Pro 50x') && !button('确认开通 Pro 50x').disabled)
  assert(document.querySelector('.pro-recharge-dialog').textContent.includes('CMSNav'), 'Manual confirmation supplier missing')
  await click('确认开通 Pro 50x')
  await wait(() => fixture.orders.length === 1)
  const req = fixture.requests.find(r => r.path.endsWith('/recharge'))
  assert(req.body.provider === 'cmsnav' && req.body.plan_code === 'pro50', 'Manual request provider/plan lost')
  await wait(() => !button('关闭').disabled); await click('关闭')
  await choose('全自动开通 Pro')
  await wait(() => document.querySelector('.pro-auto-dialog'))
  assert(document.querySelector('.pro-auto-dialog').textContent.includes('CMSNav') && button('确认全自动开通 Pro 50x'), 'Automatic confirmation supplier/plan missing')
  await click('确认全自动开通 Pro 50x')
  await wait(() => fixture.requests.some(r => r.method === 'POST' && r.path.endsWith('/auto-pro')))
  const auto = fixture.requests.find(r => r.method === 'POST' && r.path.endsWith('/auto-pro'))
  assert(auto.body.provider === 'cmsnav' && auto.body.plan_code === 'pro50', 'Automatic request provider/plan lost')
  await click('关闭')
  await click('GPTPay 供应商'); await wait(() => field('查询供应商'))
  assert(field('查询供应商').value === 'cmsnav', 'Query defaults to wrong provider')
  await click('查询账户信息')
  assert(fixture.requests.some(r => r.path === '/api/gptpay/account' && r.query === '?provider=cmsnav'), 'Account query supplier lost')
  assert(document.querySelector('.orders-table').textContent.includes('CMSNav') && document.querySelector('.orders-table').textContent.includes('Pro 50x'), 'Local order supplier/plan missing')
  await fill('查询供应商', 'tokenseek')
  await fill('订单 ID（每行一个，最多 50 个）', 'old-supplier-order'); await click('查询订单状态')
  assert(fixture.requests.findLast(r => r.path === '/api/gptpay/orders/query').body.provider === 'tokenseek', 'Manual order query supplier lost')
  await click('Pro 全自动配置'); await wait(() => field('开通供应商') && !field('开通供应商').disabled)
  assert(field('开通套餐').value === 'pro50' && field('开通供应商').value === 'cmsnav', 'Selected provider did not persist')
  return 'Passed: provider/key isolation, 50x, draft preservation, shared card cap, manual/automatic confirmation and requests, order labels, account/order query routing, saved settings'
})()
