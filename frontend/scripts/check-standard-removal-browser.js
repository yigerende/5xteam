(async () => {
  const fixture = window.standardRemovalFixture
  if (!fixture) throw new Error('Requires isolated standard removal fixture')
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
  const assert = (v, m) => { if (!v) throw new Error(m) }
  const wait = async fn => { for (let i = 0; i < 200; i++) { if (fn()) return; await pause(25) } throw new Error('UI did not update') }
  const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text)
  const toggle = () => [...document.querySelectorAll('.auto-fields label')].find(l => l.textContent.includes('移出前转普通'))?.querySelector('input')
  const selected = () => [...document.querySelectorAll('.switch-admin-list input:checked')].map(el => el.value)
  await wait(() => document.querySelectorAll('.stage-strip').length === 5)
  assert(document.querySelectorAll('.stage-strip .spin').length === 3, 'Active removal stages lack spinners')
  for (const item of fixture.items) assert(document.body.textContent.includes(item.standard_removal.message), 'Missing step message: ' + item.standard_removal.stage)
  assert(document.querySelector('.table-note.danger-text')?.textContent.includes('切换失败'), 'Failure is not visibly distinguished')
  button('全自动轮转').click(); await wait(toggle)
  assert(!toggle().checked && !document.querySelector('.switch-admins'), 'Legacy settings should default off')
  toggle().click(); await pause(25)
  assert(document.querySelectorAll('.switch-admin-list input').length === 3, 'Mother checklist missing')
  button('保存配置').click(); await pause(25)
  assert(document.body.textContent.includes('至少选择一个'), 'Empty selection accepted')
  assert(!fixture.requests.some(r => r.method === 'PUT'), 'Invalid form submitted')
  document.querySelector('.switch-admin-list input[value="mother-1"]').click(); await pause(25)
  document.querySelector('.switch-admin-list input[value="mother-3"]').click(); await pause(25)
  button('保存配置').click(); await wait(() => fixture.settings.switch_before_remove)
  assert(JSON.stringify(fixture.settings.switch_before_remove_admin_ids) === JSON.stringify(['mother-1', 'mother-3']), 'Wrong selected mothers saved')
  assert(fixture.settings.remove_method === 'child_leave', 'Removal method changed')
  button('账号管理').click(); await pause(25); button('全自动轮转').click(); await wait(toggle)
  assert(toggle().checked && selected().length === 2, 'Saved selection lost after tab change')
  document.querySelector('.switch-admins > label input').click(); await pause(25)
  assert(selected().length === 3, 'Select all failed')
  document.querySelector('.switch-admins > label input').click(); await pause(25)
  assert(selected().length === 0, 'Clear all failed')
  toggle().click(); await pause(25); button('保存配置').click(); await pause(25)
  assert(!fixture.settings.switch_before_remove, 'Cannot disable with no mothers')
  toggle().click(); await pause(25); document.querySelector('.switch-admin-list input[value="mother-2"]').click(); await pause(25); button('保存配置').click(); await pause(25)
  assert(fixture.settings.switch_before_remove_admin_ids[0] === 'mother-2', 'Final saved selection wrong')
  return 'PASS: default off, mother multi-select/select all, validation, save and remount; step progress/spinners/failure/completion displayed'
})()
